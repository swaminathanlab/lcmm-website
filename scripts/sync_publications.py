"""Refresh data/publications.yaml from Europe PMC.

Search: everything linked to the PI's ORCID, plus "Swaminathan V" papers with a
Lund / NIH / UNC / lab-member footprint (catches papers where the ORCID was not
attached). New papers are added; papers already listed are updated but never
dropped by the sync (remove one with `hide:` in data/publications_overrides.yaml).

Run by .github/workflows/sync-publications.yml every Monday; locally:
    python scripts/sync_publications.py
"""
from __future__ import annotations

import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PUBS = ROOT / "data" / "publications.yaml"
SITE = ROOT / "data" / "site.yaml"
API = "https://www.ebi.ac.uk/europepmc/webservices/rest/search"

HEADER = (
    "# Generated by scripts/sync_publications.py from Europe PMC (your ORCID plus a name/affiliation\n"
    "# search). Do not edit by hand: corrections go in data/publications_overrides.yaml.\n"
)


def query(orcid: str) -> str:
    name = 'AUTH:"Swaminathan V"'
    footprint = " OR ".join(
        [
            'AFF:"Lund"',
            'AUTH:"Waterman CM"',
            'AUTH:"Superfine R"',
            'AUTH:"Packirisamy S"',
            'AUTH:"Sakthivel K"',
            'AUTH:"Engstrom L"',
        ]
    )
    return f'AUTHORID:"{orcid}" OR ({name} AND ({footprint}))'


def fetch(q: str) -> list[dict]:
    results, cursor = [], "*"
    while True:
        params = urllib.parse.urlencode(
            {"query": q, "format": "json", "resultType": "core", "pageSize": 100, "cursorMark": cursor}
        )
        with urllib.request.urlopen(f"{API}?{params}", timeout=60) as r:
            data = json.load(r)
        page = data.get("resultList", {}).get("result", [])
        results += page
        nxt = data.get("nextCursorMark")
        if not page or not nxt or nxt == cursor:
            return results
        cursor = nxt


def convert(r: dict) -> dict | None:
    """One Europe PMC 'core' record -> our entry, or None if unusable."""
    title = (r.get("title") or "").strip().rstrip(".")
    year = r.get("pubYear")
    if not title or not year:
        return None
    authors = [
        f"{a.get('lastName', '')} {a.get('initials', '')}".strip()
        for a in r.get("authorList", {}).get("author", [])
        if a.get("lastName")
    ] or [s.strip() for s in (r.get("authorString") or "").rstrip(".").split(",") if s.strip()]
    types = [t.lower() for t in r.get("pubTypeList", {}).get("pubType", [])]
    journal = (r.get("journalInfo", {}).get("journal", {}) or {})
    jname = journal.get("isoabbreviation") or journal.get("title") or r.get("bookOrReportDetails", {}).get("publisher")
    if r.get("source") == "PPR":
        jname = (r.get("bookOrReportDetails") or {}).get("publisher") or "Preprint"
    entry = {"title": title, "authors": authors, "journal": jname or "", "year": int(year)}
    if r.get("doi"):
        entry["doi"] = r["doi"].lower()
    if r.get("pmid"):
        entry["pmid"] = str(r["pmid"])
    if r.get("source") == "PPR" or "preprint" in types:
        entry["preprint"] = True
    if "retracted publication" in types:
        return None   # retracted papers are never stored or listed
    if any(t in types for t in ("review", "review-article", "comment", "editorial")):
        entry["kind"] = "review"
    if any(t in types for t in ("retraction of publication", "published erratum", "erratum")):
        return None
    return entry


def keys(e: dict) -> set[str]:
    return {k for k in (e.get("pmid"), (e.get("doi") or "").lower()) if k}


def merge(old: list[dict], new: list[dict]) -> list[dict]:
    """Union of old and new; a new record replaces the old one it matches."""
    out = list(old)
    for n in new:
        hit = next((i for i, o in enumerate(out) if keys(o) & keys(n)), None)
        if hit is None:
            out.append(n)
        else:
            out[hit] = {**out[hit], **n}
    out.sort(key=lambda e: (-int(e["year"]), e["title"].lower()))
    return out


def main() -> int:
    site = yaml.safe_load(SITE.read_text())
    orcid = site["contact"]["orcid"]
    old = yaml.safe_load(PUBS.read_text()) or [] if PUBS.exists() else []
    try:
        raw = fetch(query(orcid))
    except Exception as exc:  # network trouble: keep the current list
        print(f"Europe PMC unreachable ({exc}); publications left unchanged.", file=sys.stderr)
        return 0
    new = [e for e in (convert(r) for r in raw) if e]
    merged = merge(old, new)
    added = len(merged) - len(old)
    PUBS.write_text(HEADER + yaml.safe_dump(merged, allow_unicode=True, sort_keys=False, width=200))
    print(f"{len(raw)} records from Europe PMC, {added} new, {len(merged)} listed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
